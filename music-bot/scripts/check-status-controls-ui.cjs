const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = new URL(process.env.PREVIEW_URL || 'http://127.0.0.1:8788/');
assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(base.hostname), 'Mutations are permitted only on local preview');
const output = path.resolve('data/screenshots'); fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(20000);
  const errors = [], posts = [], checks = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (new URL(request.url()).origin === base.origin && request.method() === 'POST') posts.push({ path: new URL(request.url()).pathname, body: request.postDataJSON() }); });
  const read = async (route) => (await (await page.request.get(new URL('/api' + route, base).href)).json());
  const state = (id) => read(`/state?botId=${id}`);
  const card = (id) => page.locator(`[data-status-bot="${id}"]`);
  const button = (id, action) => card(id).locator(`[data-status-action="${action}"]`);
  const slider = (id) => card(id).locator('[data-status-volume]');
  const ready = async (id) => page.waitForFunction((id) => document.querySelector(`[data-status-bot="${id}"]`)?.getAttribute('aria-busy') === 'false', id);
  const setVolume = async (id, value) => { await slider(id).evaluate((input, value) => { input.value = value; input.dispatchEvent(new Event('change', { bubbles: true })); }, value); await ready(id); };
  const pass = (message) => { checks.push(message); console.log(`PASS ${message}`); };
  const identity = (s) => ({ context: s.player.context, current: s.player.current, queue: s.player.queue, volume: s.player.volume, status: s.player.status });
  try {
    await page.goto(base.href, { waitUntil: 'networkidle' });
    assert.equal((await state('default')).preview, true);
    await page.locator('.nav-item[data-view="status"]').click();
    await card('preview-two').filter({ hasText: '深夜电台' }).waitFor();
    await ready('default'); await ready('preview-two');
    const baseline = await state('default'), second = await state('preview-two');
    assert.equal(await button('default', 'previous').isDisabled(), true);
    await button('default', 'pause').click(); await ready('default');
    assert.equal((await state('default')).player.status, 'paused');
    await button('default', 'resume').click(); await ready('default');
    assert.equal((await state('default')).player.status, 'playing');
    await button('default', 'skip').click(); await ready('default');
    assert.equal((await state('default')).player.current.id, baseline.player.queue[0].id);
    assert.equal(await button('default', 'previous').isEnabled(), true);
    await button('default', 'previous').click(); await ready('default');
    const returned = await state('default');
    assert.equal(returned.player.current.id, baseline.player.current.id);
    assert.deepEqual(returned.player.queue, baseline.player.queue);
    assert.deepEqual(identity(await state('preview-two')), identity(second));
    assert.equal(await page.locator('#bot-select').inputValue(), 'default');
    pass('pause, resume, next and real previous target their card, retain queue order and preserve the other bot');

    await slider('default').scrollIntoViewIfNeeded();
    const originalSlider = await slider('default').elementHandle(), box = await slider('default').boundingBox();
    const beforeVolumePosts = posts.filter((p) => p.body.action === 'volume').length;
    await page.mouse.move(box.x + box.width * 0.6, box.y + box.height / 2); await page.mouse.down();
    await page.mouse.move(box.x + box.width * 0.27, box.y + box.height / 2);
    const draft = Number(await slider('default').inputValue());
    await page.evaluate(() => document.getElementById('refresh-bot-status').click());
    await page.waitForFunction(() => !document.getElementById('refresh-bot-status').disabled);
    assert.equal(await originalSlider.evaluate((node) => node === document.querySelector('[data-status-volume="default"]')), true);
    assert.equal(Number(await slider('default').inputValue()), draft);
    await page.mouse.up(); await ready('default');
    await page.waitForFunction((value) => document.querySelector('[data-status-volume="default"]').value === String(value), draft);
    assert.equal((await state('default')).player.volume, draft);
    assert.equal(posts.filter((p) => p.body.action === 'volume').length - beforeVolumePosts, 1);
    await slider('default').focus(); await page.keyboard.press('ArrowRight'); await ready('default');
    assert.equal((await state('default')).player.volume, draft + 1);
    assert.equal(posts.filter((p) => p.body.action === 'volume').length - beforeVolumePosts, 2);
    assert.equal((await state('preview-two')).player.volume, second.player.volume);
    pass('pointer and keyboard volume changes commit once and the same slider survives refresh during dragging');

    let releaseHot, startedHot;
    const heldHot = new Promise((resolve) => { releaseHot = resolve; });
    const hotStarted = new Promise((resolve) => { startedHot = resolve; });
    const holdHot = async (route) => {
      const body = route.request().postDataJSON();
      if (body.botId !== 'default') return route.continue();
      startedHot(); await heldHot; return route.continue();
    };
    await page.route('**/api/hot', holdHot);
    const beforeHot = await state('default');
    await card('default').locator('[data-status-hot="netease"]').click(); await hotStarted;
    assert.equal(await card('default').locator('[data-status-hot="netease"]').isDisabled(), true);
    assert.equal(await slider('preview-two').isEnabled(), true);
    await setVolume('preview-two', 44); assert.equal((await state('preview-two')).player.volume, 44);
    releaseHot(); await ready('default'); await page.unroute('**/api/hot', holdHot);
    assert.equal((await state('default')).player.queue.length - beforeHot.player.queue.length, 123);
    assert.equal((await state('default')).player.current.id, beforeHot.player.current.id);
    assert.match(await card('default').locator('[data-status-feedback]').innerText(), /123/);
    pass('a pending hot-chart import locks only its card, appends the full list and reports its actual size');

    const beforeQQ = posts.filter((p) => p.path === '/api/hot' && p.body.source === 'qq').length;
    await card('preview-two').locator('[data-status-hot="qq"]').click(); await ready('preview-two');
    await card('preview-two').locator('[data-status-login]').waitFor({ state: 'visible' });
    assert.equal(posts.filter((p) => p.path === '/api/hot' && p.body.source === 'qq').length, beforeQQ);
    const session = await read('/session');
    const qr = await page.request.post(new URL('/api/account/qr', base).href, { data: { source: 'qq', type: 'qq' }, headers: { 'X-CSRF-Token': session.csrf } });
    assert.equal(qr.status(), 200); await read('/account/qr?source=qq'); await read('/account/qr?source=qq');
    const beforeQQState = await state('preview-two');
    await card('preview-two').locator('[data-status-hot="qq"]').click(); await ready('preview-two');
    const qqState = await state('preview-two');
    assert.equal(qqState.player.queue.length - beforeQQState.player.queue.length, 123);
    assert.ok(qqState.player.queue.slice(-123).every((track) => track.source === 'qq'));
    assert.equal(qqState.player.status, 'paused');
    assert.equal(posts.filter((p) => p.path === '/api/hot').every((p) => p.body.full === true && typeof p.body.botId === 'string'), true);
    pass('QQ shortcut requires login, then imports QQ songs to the intended paused bot without starting another bot');

    await card('preview-two').locator('[data-control-bot]').click(); await page.locator('#view-player').waitFor({ state: 'visible' });
    await page.locator('.nav-item[data-view="status"]').click(); await ready('default');
    let releaseState, startedState, deliveredState, held = false;
    const heldState = new Promise((resolve) => { releaseState = resolve; });
    const stateStarted = new Promise((resolve) => { startedState = resolve; });
    const stateDelivered = new Promise((resolve) => { deliveredState = resolve; });
    const delayState = async (route) => {
      if (new URL(route.request().url()).searchParams.get('botId') !== 'default' || held) return route.continue();
      held = true; const response = await route.fetch(); startedState(); await heldState; await route.fulfill({ response }); deliveredState();
    };
    await page.route('**/api/state?*', delayState);
    await page.locator('#refresh-bot-status').click(); await stateStarted;
    await setVolume('default', 53); assert.equal((await state('default')).player.volume, 53);
    releaseState(); await stateDelivered; await page.unroute('**/api/state?*', delayState);
    await page.waitForFunction(() => !document.getElementById('refresh-bot-status').disabled);
    assert.equal(Number(await slider('default').inputValue()), 53);
    assert.equal(await page.locator('#bot-select').inputValue(), 'preview-two');
    const rejectVolume = (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '测试：音量请求失败' }) });
    await page.route('**/api/control', rejectVolume);
    await setVolume('preview-two', 77);
    await card('preview-two').locator('[data-status-feedback]').filter({ hasText: '音量请求失败' }).waitFor();
    assert.equal(Number(await slider('preview-two').inputValue()), 44);
    assert.equal((await state('preview-two')).player.volume, 44);
    await page.unroute('**/api/control', rejectVolume);
    pass('late polls cannot overwrite a new setting; failed volume writes restore the actual setting without retargeting');

    for (const width of [1440, 801, 390, 360]) {
      await page.setViewportSize({ width, height: width > 800 ? 1000 : 844 });
      await card('default').locator('.status-controls').scrollIntoViewIfNeeded();
      await page.screenshot({ path: path.join(output, `status-controls-${width}.png`) });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      assert.equal(await slider('default').isVisible(), true);
    }
    pass('card controls remain readable and reachable across desktop and narrow mobile layouts');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ checks, errors, posts: posts.map((p) => ({ route: p.path, botId: p.body.botId, action: p.body.action, source: p.body.source })), screenshots: output }));
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
